#!/usr/bin/env python3
"""Generate C and Python code from the shared CAN definitions in defs/.

Reads defs/rover.dbc, defs/errors.yaml and defs/params/*.yaml and writes:

  firmware/generated/rover.h / rover.c     DBC pack/unpack (cantools generate_c_source)
  firmware/generated/errors.h              error codes, severities, a lookup table
  firmware/generated/params_<type>.h       one per defs/params/<type>.yaml
  firmware/generated/ids.h                 class/node-ID constants and the ID helper macro
  defs/generated/python/anv_can_defs/      the same four things as a Python package

Idempotent: with no change to the source files, running this twice produces byte-identical
output (cantools' own per-run timestamp comment is normalized away). Run it after editing
rover.dbc, errors.yaml or any params/*.yaml file and commit the regenerated files; CI checks
that nobody forgets with `generate.py && git diff --exit-code`.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import cantools
import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFS_DIR = REPO_ROOT / "defs"
DBC_PATH = DEFS_DIR / "rover.dbc"
ERRORS_PATH = DEFS_DIR / "errors.yaml"
PARAMS_DIR = DEFS_DIR / "params"
FW_GEN_DIR = REPO_ROOT / "firmware" / "generated"
PY_GEN_DIR = REPO_ROOT / "defs" / "generated" / "python" / "anv_can_defs"

DO_NOT_EDIT_C = """\
/* Generated by defs/codegen/generate.py from {source}. DO NOT EDIT.
 * Regenerate with: python defs/codegen/generate.py
 */
"""
DO_NOT_EDIT_PY = '''\
"""Generated by defs/codegen/generate.py from {source}. DO NOT EDIT.

Regenerate with: python defs/codegen/generate.py
"""
'''

# Node IDs from docs/architecture.md "Identifier scheme". Kept here once so the ID header
# and the ID helpers module can't drift from each other.
CAN_CLASSES = [
    (0, "NETWORK", "E-stop, SYNC, network management, host heartbeats"),
    (1, "COMMAND", "Commands to nodes"),
    (2, "FEEDBACK", "Fast feedback"),
    (3, "TELEMETRY", "Slow telemetry"),
    (4, "SENSOR", "Sensor streams"),
    (5, "SERVICE", "Parameters, node info"),
    (6, "HEARTBEAT", "Node heartbeats"),
    (7, "BOOTLOADER", "Bootloader and firmware transfer"),
]

NODE_IDS = {
    "BROADCAST": 0,
    "ORIN": 1,
    "RPI": 2,
    "TOOL": 3,
    "DRIVE1": 4,
    "DRIVE2": 5,
    "DRIVE3": 6,
    "DRIVE4": 7,
    "DRIVE5": 8,
    "DRIVE6": 9,
    "FPGA": 20,
    "UNCONFIGURED": 31,
}

C_TYPES = {
    "u8": "uint8_t",
    "u16": "uint16_t",
    "u32": "uint32_t",
    "i8": "int8_t",
    "i16": "int16_t",
    "i32": "int32_t",
    "f32": "float",
}


def run_cantools_generate_c_source() -> None:
    FW_GEN_DIR.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            sys.executable, "-m", "cantools", "generate_c_source",
            "--no-floating-point-numbers",
            "--database-name", "rover",
            "-o", str(FW_GEN_DIR),
            str(DBC_PATH),
        ],
        check=True,
        cwd=REPO_ROOT,
    )
    # cantools stamps "generated by cantools version X.Y.Z <weekday> <date> <time>" into a
    # comment, which would otherwise make every regeneration look like a diff. Normalize it.
    timestamp_re = re.compile(r"generated by cantools version [^\n]*\.")
    for name in ("rover.h", "rover.c"):
        path = FW_GEN_DIR / name
        text = path.read_text()
        text = timestamp_re.sub("generated by cantools.", text)
        path.write_text(text)


def load_errors() -> list[dict]:
    data = yaml.safe_load(ERRORS_PATH.read_text())
    return data["errors"]


def load_param_files() -> list[tuple[str, list[dict]]]:
    out = []
    for path in sorted(PARAMS_DIR.glob("*.yaml")):
        data = yaml.safe_load(path.read_text())
        out.append((data["node_type"], data["parameters"]))
    return out


SEVERITY_VALUES = {"info": 0, "warning": 1, "error": 2, "critical": 3}


def generate_errors_c(errors: list[dict]) -> str:
    lines = [DO_NOT_EDIT_C.format(source="defs/errors.yaml")]
    lines.append("#ifndef ROVER_ERRORS_H")
    lines.append("#define ROVER_ERRORS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif")
    lines.append("")
    lines.append("typedef enum {")
    lines.append("    ROVER_SEVERITY_INFO = 0,")
    lines.append("    ROVER_SEVERITY_WARNING = 1,")
    lines.append("    ROVER_SEVERITY_ERROR = 2,")
    lines.append("    ROVER_SEVERITY_CRITICAL = 3,")
    lines.append("} rover_severity_t;")
    lines.append("")
    for e in errors:
        lines.append(f'#define ROVER_ERR_{e["name"]} ((uint16_t)0x{e["code"]:04X}u)')
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint16_t code;")
    lines.append("    rover_severity_t severity;")
    lines.append("    const char *name;")
    lines.append("} rover_error_info_t;")
    lines.append("")
    lines.append("static const rover_error_info_t ROVER_ERROR_TABLE[] = {")
    for e in errors:
        sev = f"ROVER_SEVERITY_{e['severity'].upper()}"
        lines.append(f'    {{ 0x{e["code"]:04X}u, {sev}, "{e["name"]}" }},')
    lines.append("};")
    lines.append("")
    lines.append("#define ROVER_ERROR_TABLE_LEN "
                  "(sizeof(ROVER_ERROR_TABLE) / sizeof(ROVER_ERROR_TABLE[0]))")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    lines.append("#endif /* ROVER_ERRORS_H */")
    return "\n".join(lines) + "\n"


def generate_errors_py(errors: list[dict]) -> str:
    lines = [DO_NOT_EDIT_PY.format(source="defs/errors.yaml")]
    lines.append("from dataclasses import dataclass")
    lines.append("from enum import IntEnum")
    lines.append("")
    lines.append("")
    lines.append("class Severity(IntEnum):")
    lines.append("    INFO = 0")
    lines.append("    WARNING = 1")
    lines.append("    ERROR = 2")
    lines.append("    CRITICAL = 3")
    lines.append("")
    lines.append("")
    lines.append("@dataclass(frozen=True)")
    lines.append("class ErrorInfo:")
    lines.append("    code: int")
    lines.append("    name: str")
    lines.append("    severity: Severity")
    lines.append("    description: str")
    lines.append("    likely_cause: str")
    lines.append("")
    lines.append("")
    lines.append("ERRORS: dict[int, ErrorInfo] = {")
    for e in errors:
        desc = e["description"].replace('"', '\\"')
        cause = e["likely_cause"].replace('"', '\\"')
        lines.append(
            f'    0x{e["code"]:04X}: ErrorInfo(0x{e["code"]:04X}, "{e["name"]}", '
            f'Severity.{e["severity"].upper()}, "{desc}", "{cause}"),'
        )
    lines.append("}")
    lines.append("")
    lines.append("")
    lines.append("def lookup(code: int) -> ErrorInfo | None:")
    lines.append('    """Look up an error code; returns None for an unknown code."""')
    lines.append("    return ERRORS.get(code)")
    return "\n".join(lines) + "\n"


def generate_params_c(node_type: str, params: list[dict]) -> str:
    guard = f"ROVER_PARAMS_{node_type.upper()}_H"
    lines = [DO_NOT_EDIT_C.format(source=f"defs/params/{node_type}.yaml")]
    lines.append(f"#ifndef {guard}")
    lines.append(f"#define {guard}")
    lines.append("")
    lines.append("#include <stdbool.h>")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif")
    lines.append("")
    for p in params:
        lines.append(f'#define ROVER_PARAM_{node_type.upper()}_{p["name"].upper()}_INDEX '
                      f'((uint16_t){p["index"]}u)')
    lines.append("")
    lines.append("typedef struct {")
    for p in params:
        lines.append(f'    {C_TYPES[p["type"]]} {p["name"]};')
    lines.append(f"}} rover_params_{node_type}_t;")
    lines.append("")
    lines.append("typedef enum {")
    for t in sorted({p["type"] for p in params}):
        lines.append(f"    ROVER_PARAM_TYPE_{t.upper()},")
    lines.append("} rover_param_type_t;")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint16_t index;")
    lines.append("    const char *name;")
    lines.append("    rover_param_type_t type;")
    lines.append("    double minimum;")
    lines.append("    double maximum;")
    lines.append("    double default_value;")
    lines.append("    bool disarmed_only;")
    lines.append("} rover_param_descriptor_t;")
    lines.append("")
    lines.append(f"static const rover_param_descriptor_t ROVER_PARAMS_{node_type.upper()}_TABLE[] = {{")
    for p in params:
        disarmed = "true" if p["disarmed_only"] else "false"
        lines.append(
            f'    {{ {p["index"]}u, "{p["name"]}", ROVER_PARAM_TYPE_{p["type"].upper()}, '
            f'{float(p["min"])}, {float(p["max"])}, {float(p["default"])}, {disarmed} }},'
        )
    lines.append("};")
    lines.append("")
    lines.append(f"#define ROVER_PARAMS_{node_type.upper()}_TABLE_LEN "
                  f"(sizeof(ROVER_PARAMS_{node_type.upper()}_TABLE) / "
                  f"sizeof(ROVER_PARAMS_{node_type.upper()}_TABLE[0]))")
    lines.append("")
    lines.append(f"static const rover_params_{node_type}_t ROVER_PARAMS_{node_type.upper()}_DEFAULTS = {{")
    for p in params:
        lines.append(f'    .{p["name"]} = {float(p["default"])},')
    lines.append("};")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    lines.append(f"#endif /* {guard} */")
    return "\n".join(lines) + "\n"


def generate_params_py(node_type: str, params: list[dict]) -> str:
    lines = [DO_NOT_EDIT_PY.format(source=f"defs/params/{node_type}.yaml")]
    lines.append("from dataclasses import dataclass")
    lines.append("")
    lines.append("")
    lines.append("@dataclass(frozen=True)")
    lines.append("class ParamInfo:")
    lines.append("    index: int")
    lines.append("    name: str")
    lines.append("    type: str")
    lines.append("    minimum: float")
    lines.append("    maximum: float")
    lines.append("    default: float")
    lines.append("    unit: str")
    lines.append("    disarmed_only: bool")
    lines.append("    description: str")
    lines.append("")
    lines.append("")
    varname = f"PARAMS_{node_type.upper()}"
    lines.append(f"{varname}: dict[int, ParamInfo] = {{")
    for p in params:
        desc = p["description"].replace('"', '\\"')
        lines.append(
            f'    {p["index"]}: ParamInfo({p["index"]}, "{p["name"]}", "{p["type"]}", '
            f'{float(p["min"])}, {float(p["max"])}, {float(p["default"])}, "{p["unit"]}", '
            f'{p["disarmed_only"]}, "{desc}"),'
        )
    lines.append("}")
    lines.append("")
    lines.append(f"{varname}_BY_NAME: dict[str, ParamInfo] = {{p.name: p for p in {varname}.values()}}")
    return "\n".join(lines) + "\n"


def generate_ids_c() -> str:
    lines = [DO_NOT_EDIT_C.format(source="docs/architecture.md (Identifier scheme)")]
    lines.append("#ifndef ROVER_IDS_H")
    lines.append("#define ROVER_IDS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif")
    lines.append("")
    lines.append("/* 11-bit ID = (class << 8) | (node << 3) | sub. */")
    lines.append("#define ROVER_CAN_ID(cls, node, sub) \\")
    lines.append("    ((uint16_t)((((uint16_t)(cls) & 0x7u) << 8) | \\")
    lines.append("                (((uint16_t)(node) & 0x1Fu) << 3) | \\")
    lines.append("                ((uint16_t)(sub) & 0x7u)))")
    lines.append("#define ROVER_ID_CLASS(id) ((uint8_t)(((id) >> 8) & 0x7u))")
    lines.append("#define ROVER_ID_NODE(id)  ((uint8_t)(((id) >> 3) & 0x1Fu))")
    lines.append("#define ROVER_ID_SUB(id)   ((uint8_t)((id) & 0x7u))")
    lines.append("")
    for cls_id, cls_name, _desc in CAN_CLASSES:
        lines.append(f"#define ROVER_CLASS_{cls_name} ((uint8_t){cls_id}u)")
    lines.append("")
    for name, node_id in NODE_IDS.items():
        lines.append(f"#define ROVER_NODE_{name} ((uint8_t){node_id}u)")
    lines.append("")
    lines.append("/* Drive node n (1-6) has node ID 3 + n and its CAN IDs are offset by")
    lines.append(" * (n - 1) * 8 from drive node 1's IDs. */")
    lines.append("#define ROVER_DRIVE_NODE_ID(n) ((uint8_t)(3u + (n)))")
    lines.append("#define ROVER_DRIVE_ID_OFFSET(n) ((uint16_t)(((n) - 1u) * 8u))")
    lines.append("")
    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    lines.append("#endif /* ROVER_IDS_H */")
    return "\n".join(lines) + "\n"


def generate_ids_py() -> str:
    lines = [DO_NOT_EDIT_PY.format(source="docs/architecture.md (Identifier scheme)")]
    lines.append("from enum import IntEnum")
    lines.append("")
    lines.append("")
    lines.append("class CanClass(IntEnum):")
    for cls_id, cls_name, desc in CAN_CLASSES:
        lines.append(f"    {cls_name} = {cls_id}  # {desc}")
    lines.append("")
    lines.append("")
    for name, node_id in NODE_IDS.items():
        lines.append(f"NODE_{name} = {node_id}")
    lines.append("")
    lines.append("")
    lines.append("def can_id(cls: int, node: int, sub: int) -> int:")
    lines.append('    """11-bit ID = (class << 8) | (node << 3) | sub."""')
    lines.append("    return ((cls & 0x7) << 8) | ((node & 0x1F) << 3) | (sub & 0x7)")
    lines.append("")
    lines.append("")
    lines.append("def id_class(frame_id: int) -> int:")
    lines.append("    return (frame_id >> 8) & 0x7")
    lines.append("")
    lines.append("")
    lines.append("def id_node(frame_id: int) -> int:")
    lines.append("    return (frame_id >> 3) & 0x1F")
    lines.append("")
    lines.append("")
    lines.append("def id_sub(frame_id: int) -> int:")
    lines.append("    return frame_id & 0x7")
    lines.append("")
    lines.append("")
    lines.append("def drive_node_id(drive_num: int) -> int:")
    lines.append('    """Drive node n (1-6) has node ID 3 + n."""')
    lines.append("    return 3 + drive_num")
    lines.append("")
    lines.append("")
    lines.append("def drive_id_offset(drive_num: int) -> int:")
    lines.append('    """CAN-ID offset of drive node n (1-6) from drive node 1\'s IDs."""')
    lines.append("    return (drive_num - 1) * 8")
    return "\n".join(lines) + "\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main() -> int:
    cantools.database.load_file(DBC_PATH)  # fail fast on a broken DBC

    run_cantools_generate_c_source()

    errors = load_errors()
    write(FW_GEN_DIR / "errors.h", generate_errors_c(errors))
    write(PY_GEN_DIR / "errors.py", generate_errors_py(errors))

    param_files = load_param_files()
    for node_type, params in param_files:
        write(FW_GEN_DIR / f"params_{node_type}.h", generate_params_c(node_type, params))
        write(PY_GEN_DIR / f"params_{node_type}.py", generate_params_py(node_type, params))

    write(FW_GEN_DIR / "ids.h", generate_ids_c())
    write(PY_GEN_DIR / "ids.py", generate_ids_py())

    init_exports = ["errors", "ids"] + [f"params_{t}" for t, _ in param_files]
    init_text = DO_NOT_EDIT_PY.format(source="defs/rover.dbc, defs/errors.yaml, defs/params/*.yaml")
    init_text += "\n" + "\n".join(f"from . import {m}" for m in init_exports) + "\n"
    write(PY_GEN_DIR / "__init__.py", init_text)

    print(f"Generated firmware/generated/ and defs/generated/python/ from "
          f"{len(errors)} error codes and {len(param_files)} parameter table(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
