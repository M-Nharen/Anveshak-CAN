"""Generate C11 for firmware: one .h/.c pair per node type, plus the protocol and a runtime header.

For every message: a struct of raw values, pack/unpack functions, and to/from-physical helpers
for scaled fields. For every type: tables describing its messages, parameters, actions and
events, tied together in one `anv_type_desc_t` that the node library reads at run time.
No allocation, no libm, no floating point unless a field or parameter is a float.
"""
from __future__ import annotations

from pathlib import Path

from .model import Field, Message, NodeType, Param, Schema, ValueType

HEADER = "/* Generated by anv_schema from {source}. DO NOT EDIT; run `anv-schema gen`. */\n"

KIND_C = {"stream": "ANV_KIND_STREAM", "event": "ANV_KIND_EVENT", "command": "ANV_KIND_COMMAND",
          "frame": "ANV_KIND_FRAME"}
SENDER_C = {"node": "ANV_SENDER_NODE", "host": "ANV_SENDER_HOST", "leader": "ANV_SENDER_LEADER",
            "any": "ANV_SENDER_ANY"}
SEVERITY_C = {"info": 0, "warning": 1, "error": 2, "critical": 3}
VT_C = {"bool": "ANV_VT_BOOL", "u8": "ANV_VT_U8", "i8": "ANV_VT_I8", "u16": "ANV_VT_U16",
        "i16": "ANV_VT_I16", "u32": "ANV_VT_U32", "i32": "ANV_VT_I32", "f32": "ANV_VT_F32"}

RUNTIME_H = r"""/* anv_schema.h: types shared by all generated schema code. DO NOT EDIT; generated. */
#ifndef ANV_SCHEMA_H
#define ANV_SCHEMA_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <string.h>

#ifdef __cplusplus
extern "C" {
#endif

/* Names in the descriptor tables cost flash; define ANV_SCHEMA_NO_NAMES to drop them. */
#ifdef ANV_SCHEMA_NO_NAMES
#define ANV_NAME(s) NULL
#else
#define ANV_NAME(s) (s)
#endif

/* Parameter / action argument value types (what a 32-bit service value means). */
typedef enum {
    ANV_VT_NONE = 0,
    ANV_VT_BOOL,
    ANV_VT_U8,
    ANV_VT_I8,
    ANV_VT_U16,
    ANV_VT_I16,
    ANV_VT_U32,
    ANV_VT_I32,
    ANV_VT_F32
} anv_value_type_t;

/* One parameter value, as carried in a SERVICE frame's 32-bit value field. */
typedef union {
    uint32_t u;
    int32_t i;
    float f;
} anv_value_t;

typedef enum { ANV_KIND_STREAM, ANV_KIND_EVENT, ANV_KIND_COMMAND, ANV_KIND_FRAME } anv_kind_t;
typedef enum { ANV_SENDER_NODE, ANV_SENDER_HOST, ANV_SENDER_LEADER, ANV_SENDER_ANY } anv_sender_t;

#define ANV_MSG_APPLY_SYNC 0x01u   /* command is held and applied at the next SYNC */

typedef struct {
    uint16_t port;
    uint8_t priority;
    uint8_t kind;               /* anv_kind_t */
    uint8_t sender;             /* anv_sender_t */
    uint8_t length;             /* bytes */
    uint8_t flags;              /* ANV_MSG_* */
    uint16_t watchdog_ms;       /* commands: 0 = no watchdog */
    uint32_t rate_default_mhz;  /* streams: rates in millihertz (0 = off) */
    uint32_t rate_min_mhz;
    uint32_t rate_max_mhz;
    const char *name;
} anv_msg_desc_t;

#define ANV_PARAM_READ_ONLY     0x01u
#define ANV_PARAM_PERSIST       0x02u
#define ANV_PARAM_DISARMED_ONLY 0x04u
#define ANV_PARAM_REBOOT        0x08u
#define ANV_PARAM_HAS_MIN       0x10u
#define ANV_PARAM_HAS_MAX       0x20u

typedef struct {
    uint16_t index;
    uint8_t type;               /* anv_value_type_t */
    uint8_t flags;              /* ANV_PARAM_* */
    anv_value_t def;
    anv_value_t min;
    anv_value_t max;
    const char *name;
    const char *unit;
} anv_param_desc_t;

#define ANV_ACTION_DISARMED_ONLY 0x01u

typedef struct {
    uint16_t index;
    uint8_t arg_type;           /* anv_value_type_t, ANV_VT_NONE = no argument */
    uint8_t flags;              /* ANV_ACTION_* */
    const char *name;
} anv_action_desc_t;

typedef struct {
    uint16_t code;
    uint8_t severity;           /* 0 info, 1 warning, 2 error, 3 critical */
    const char *name;
} anv_event_desc_t;

/* Everything a node of one type can do. The node library works only from this. */
typedef struct {
    const char *name;
    uint16_t type_id;
    uint16_t version;
    uint32_t wire_hash;
    const anv_msg_desc_t *messages;
    uint16_t n_messages;
    const anv_param_desc_t *params;
    uint16_t n_params;
    const anv_action_desc_t *actions;
    uint16_t n_actions;
    const anv_event_desc_t *events;
    uint16_t n_events;
} anv_type_desc_t;

/* --- bit helpers used by the generated pack/unpack code ------------------------------ */
/* A frame is one little-endian 64-bit integer; a field of n bits at bit s is
 * (frame >> s) & mask(n). Same rule as DBC "Intel" byte order. */

static inline uint64_t anv_bits_load(const uint8_t *data, uint8_t len)
{
    uint64_t v = 0;
    for (uint8_t i = 0; i < len && i < 8; i++) {
        v |= (uint64_t)data[i] << (8u * i);
    }
    return v;
}

static inline void anv_bits_store(uint64_t v, uint8_t *out, uint8_t len)
{
    for (uint8_t i = 0; i < len && i < 8; i++) {
        out[i] = (uint8_t)(v >> (8u * i));
    }
}

static inline uint64_t anv_bits_mask(uint8_t bits)
{
    return bits >= 64 ? UINT64_MAX : (((uint64_t)1 << bits) - 1u);
}

static inline uint64_t anv_bits_get(uint64_t frame, uint8_t start, uint8_t bits)
{
    return (frame >> start) & anv_bits_mask(bits);
}

static inline uint64_t anv_bits_put(uint64_t value, uint8_t start, uint8_t bits)
{
    return (value & anv_bits_mask(bits)) << start;
}

static inline int64_t anv_bits_signed(uint64_t raw, uint8_t bits)
{
    if (bits >= 64) {
        return (int64_t)raw;
    }
    uint64_t sign = (uint64_t)1 << (bits - 1);
    return (int64_t)((raw ^ sign) - sign);
}

static inline uint32_t anv_f32_bits(float f)
{
    uint32_t u;
    memcpy(&u, &f, sizeof u);
    return u;
}

static inline float anv_bits_f32(uint64_t raw)
{
    uint32_t u = (uint32_t)raw;
    float f;
    memcpy(&f, &u, sizeof f);
    return f;
}

/* Physical values in the generated *_to_phys / *_from_phys helpers. float by default: the
 * ESP32's FPU is single precision and double is done in software. Define
 * ANV_SCHEMA_PHYS_DOUBLE for double (e.g. a 32-bit field with a fine scale). */
#ifdef ANV_SCHEMA_PHYS_DOUBLE
typedef double anv_phys_t;
#else
typedef float anv_phys_t;
#endif

/* Round a physical value to the nearest raw integer and clamp it to [lo, hi]. */
static inline int64_t anv_round_clamp(anv_phys_t v, int64_t lo, int64_t hi)
{
    if (v != v) {
        return 0; /* NaN */
    }
    if (v <= (anv_phys_t)lo) {
        return lo;
    }
    if (v >= (anv_phys_t)hi) {
        return hi;
    }
    return (int64_t)(v >= 0 ? v + (anv_phys_t)0.5 : v - (anv_phys_t)0.5);
}

#ifdef __cplusplus
}
#endif

#endif /* ANV_SCHEMA_H */
"""


def prefix(t: NodeType) -> str:
    """C prefix: `anv_` for the protocol, `anv_<type>_` for a node type."""
    return "anv_" if t.type_id == 0 else f"anv_{t.name}_"


def _num(v: float) -> str:
    """A C literal for a double that reads back exactly."""
    r = repr(float(v))
    if "e" not in r and "." not in r and "inf" not in r and "nan" not in r:
        r += ".0"
    return r


def _f32(v: float) -> str:
    return _num(v) + "f"


def _value_init(vt: ValueType, v: float | None) -> str:
    if v is None:
        return "{.u = 0u}"
    if vt.is_float:
        return f"{{.f = {_f32(v)}}}"
    if vt.signed:
        return f"{{.i = {int(v)}}}"
    return f"{{.u = {int(v)}u}}"


def _mhz(hz: float) -> str:
    return f"{round(hz * 1000)}u"


def _cstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _comment(f: Field) -> str:
    bits = [f"bits {f.start_bit}..{f.start_bit + f.bits - 1}"]
    if f.is_scaled:
        bits.append(f"phys = raw * {f.scale:g} + {f.offset:g}")
    if f.unit:
        bits.append(f.unit)
    if f.enum is not None:
        bits.append(f"enum {f.enum.name}")
    if f.const is not None:
        bits.append(f"always {f.const:#x}")
    if f.description:
        bits.append(f.description)
    return "; ".join(bits)


# --- per message ------------------------------------------------------------------------

def _msg_decls(t: NodeType, m: Message, schema: Schema) -> list[str]:
    p = prefix(t)
    name = f"{p}{m.name}"
    up = name.upper()
    out = [f"/* {m.name}: {m.description}".rstrip(": ") + " */" if m.description
           else f"/* {m.name} */"]
    out.append(f"#define {up}_PORT {m.port}u")
    out.append(f"#define {up}_PRIORITY {m.priority}u")
    out.append(f"#define {up}_LENGTH {m.length}u")
    if m.kind == "frame":
        out.append("")
        return out
    out.append("typedef struct {")
    if not m.fields:
        out.append("    uint8_t unused_; /* no fields */")
    for f in m.fields:
        arr = f"[{f.count}]" if f.count > 1 else ""
        out.append(f"    {f.type.c_type} {f.name}{arr}; /* {_comment(f)} */")
    out.append(f"}} {name}_t;")
    out.append(f"/* Writes {m.length} bytes to out; returns the frame length. */")
    out.append(f"uint8_t {name}_pack(uint8_t out[8], const {name}_t *m);")
    out.append(f"/* False if len is shorter than {m.length}"
               + (" or a constant field is wrong" if any(f.const is not None for f in m.fields)
                  else "") + ". */")
    out.append(f"bool {name}_unpack({name}_t *m, const uint8_t *data, uint8_t len);")
    for f in m.fields:
        if f.is_scaled and not f.type.is_float:
            ct = f.type.c_type
            fn = f"{name}_{f.name}"
            sc, off = f"(anv_phys_t){_num(f.scale)}", f"(anv_phys_t){_num(f.offset)}"
            out.append(f"static inline anv_phys_t {fn}_to_phys({ct} raw)")
            out.append(f"{{ return (anv_phys_t)raw * {sc} + {off}; }}")
            out.append(f"static inline {ct} {fn}_from_phys(anv_phys_t phys)")
            out.append(f"{{ return ({ct})anv_round_clamp((phys - {off}) / {sc}, "
                       f"{_int_lit(f.type.raw_min)}, {_int_lit(f.type.raw_max)}); }}")
    out.append("")
    return out


def _int_lit(v: int) -> str:
    if v > (1 << 63) - 1:
        return "INT64_MAX"     # u64 scaled fields: clamp to what the helper can hold
    if v == -(1 << 63):
        return "INT64_MIN"
    if v < 0:
        return f"(int64_t){v}"
    return f"(int64_t){v}u" if v > 0x7FFFFFFF else str(v)


def _pack_expr(f: Field, ref: str) -> str:
    t = f.type
    if t.is_float:
        return f"(uint64_t)anv_f32_bits({ref})"
    if t.is_bool:
        return f"(uint64_t)({ref} ? 1u : 0u)"
    if t.signed:
        return f"(uint64_t)(int64_t){ref}"
    return f"(uint64_t){ref}"


def _unpack_expr(f: Field, start: str) -> str:
    t = f.type
    get = f"anv_bits_get(v, {start}, {t.bits}u)"
    if t.is_float:
        return f"anv_bits_f32({get})"
    if t.is_bool:
        return f"{get} != 0u"
    if t.signed:
        return f"({t.c_type})anv_bits_signed({get}, {t.bits}u)"
    return f"({t.c_type}){get}"


def _msg_defs(t: NodeType, m: Message) -> list[str]:
    if m.kind == "frame":
        return []
    name = f"{prefix(t)}{m.name}"
    out = [f"uint8_t {name}_pack(uint8_t out[8], const {name}_t *m)", "{"]
    if not m.fields:
        out += ["    (void)m;", "    memset(out, 0, 8);", f"    return {m.length}u;", "}", ""]
    else:
        out.append("    uint64_t v = 0;")
        for f in m.fields:
            if f.const is not None:
                out.append(f"    v |= anv_bits_put({f.const:#x}u, {f.start_bit}u, {f.type.bits}u);"
                           f" /* {f.name} */")
            elif f.count > 1:
                out.append(f"    for (unsigned i = 0; i < {f.count}u; i++) {{")
                out.append(f"        v |= anv_bits_put({_pack_expr(f, f'm->{f.name}[i]')}, "
                           f"(uint8_t)({f.start_bit}u + i * {f.type.bits}u), {f.type.bits}u);")
                out.append("    }")
            else:
                out.append(f"    v |= anv_bits_put({_pack_expr(f, f'm->{f.name}')}, "
                           f"{f.start_bit}u, {f.type.bits}u);")
        out += ["    memset(out, 0, 8);", f"    anv_bits_store(v, out, {m.length}u);",
                f"    return {m.length}u;", "}", ""]

    out += [f"bool {name}_unpack({name}_t *m, const uint8_t *data, uint8_t len)", "{"]
    out.append(f"    if (len < {m.length}u) {{")
    out += ["        return false;", "    }"]
    if not m.fields:
        out += ["    (void)data;", "    memset(m, 0, sizeof *m);", "    return true;", "}", ""]
        return out
    out.append(f"    uint64_t v = anv_bits_load(data, {m.length}u);")
    for f in m.fields:
        if f.count > 1:
            out.append(f"    for (unsigned i = 0; i < {f.count}u; i++) {{")
            start = f"(uint8_t)({f.start_bit}u + i * {f.type.bits}u)"
            out.append(f"        m->{f.name}[i] = {_unpack_expr(f, start)};")
            out.append("    }")
        else:
            out.append(f"    m->{f.name} = {_unpack_expr(f, f'{f.start_bit}u')};")
    consts = [f for f in m.fields if f.const is not None]
    for f in consts:
        out.append(f"    if (anv_bits_get(v, {f.start_bit}u, {f.type.bits}u) != {f.const:#x}u) {{")
        out += ["        return false;", "    }"]
    out += ["    return true;", "}", ""]
    return out


# --- per type ---------------------------------------------------------------------------

def _param_flags(p: Param) -> str:
    flags = []
    if p.access == "ro":
        flags.append("ANV_PARAM_READ_ONLY")
    if p.persist:
        flags.append("ANV_PARAM_PERSIST")
    if p.disarmed_only:
        flags.append("ANV_PARAM_DISARMED_ONLY")
    if p.reboot_required:
        flags.append("ANV_PARAM_REBOOT")
    if p.min is not None:
        flags.append("ANV_PARAM_HAS_MIN")
    if p.max is not None:
        flags.append("ANV_PARAM_HAS_MAX")
    return " | ".join(flags) or "0u"


def generate_type(schema: Schema, t: NodeType) -> tuple[str, str]:
    """(header, source) for one node type (or the protocol)."""
    p = prefix(t)
    guard = f"{p.upper()}H" if t.type_id else "ANV_PROTOCOL_H"
    fname = "anv_protocol" if t.type_id == 0 else f"anv_{t.name}"
    h: list[str] = [HEADER.format(source=Path(t.source).name if t.source else t.name),
                    f"#ifndef {guard}", f"#define {guard}", "", '#include "anv_schema.h"']
    if t.type_id != 0:
        h.append('#include "anv_protocol.h"')
    h += ["", "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    if t.description:
        h.append(f"/* {t.name}: {t.description} */")
    h += [f"#define {p.upper()}TYPE_ID {t.type_id}u" if t.type_id else "#define ANV_PROTOCOL_TYPE_ID 0u",
          f"#define {p.upper()}VERSION {t.version}u" if t.type_id else
          f"#define ANV_PROTOCOL_VERSION {t.version}u",
          (f"#define {p.upper()}WIRE_HASH {t.wire_hash:#010x}u" if t.type_id else
           f"#define ANV_PROTOCOL_WIRE_HASH {t.wire_hash:#010x}u"), ""]

    if t.type_id == 0:
        h += _id_layout_decls(schema)

    for ename, e in t.enums.items():
        en = f"{p}{ename}"
        h.append("typedef enum {")
        for label, v in e.values.items():
            h.append(f"    {en.upper()}_{label.upper()} = {v},")
        h.append(f"}} {en}_t;")
        h.append("")

    for m in t.messages:
        h += _msg_decls(t, m, schema)

    if t.params:
        h.append("/* Parameters (SERVICE index) */")
        for prm in t.params:
            h.append(f"#define {p.upper()}PARAM_{prm.name.upper()} {prm.index:#06x}u")
        h.append("")
    if t.actions:
        h.append("/* Actions (SERVICE op ACTION, index) */")
        for a in t.actions:
            h.append(f"#define {p.upper()}ACTION_{a.name.upper()} {a.index}u")
        h.append("")
    if t.events:
        h.append("/* Event codes */")
        for e in t.events:
            h.append(f"#define {p.upper()}EVENT_{e.name.upper()} {e.code:#06x}u")
        h.append("")

    tname = "anv_protocol" if t.type_id == 0 else f"anv_{t.name}"
    h += [f"extern const anv_msg_desc_t {tname}_messages[];",
          f"extern const anv_param_desc_t {tname}_params[];",
          f"extern const anv_action_desc_t {tname}_actions[];",
          f"extern const anv_event_desc_t {tname}_events[];",
          f"/* Everything about this {'protocol' if t.type_id == 0 else 'node type'} in one place. */",
          f"extern const anv_type_desc_t {tname}_type;", "",
          "#ifdef __cplusplus", "}", "#endif", "", f"#endif /* {guard} */", ""]

    c: list[str] = [HEADER.format(source=Path(t.source).name if t.source else t.name),
                    f'#include "{fname}.h"', ""]
    for m in t.messages:
        c += _msg_defs(t, m)

    def table(ctype: str, name: str, rows: list[str]) -> list[str]:
        if not rows:
            # C has no empty arrays; one zero row keeps the symbol, the count stays 0.
            return [f"const {ctype} {name}[1] = {{{{0}}}};", ""]
        return [f"const {ctype} {name}[] = {{", *rows, "};", ""]

    c += table("anv_msg_desc_t", f"{tname}_messages", [
        f"    {{{m.port}u, {m.priority}u, {KIND_C[m.kind]}, {SENDER_C[m.sender]}, {m.length}u, "
        f"{'ANV_MSG_APPLY_SYNC' if m.apply == 'sync' else '0u'}, {m.watchdog_ms}u, "
        + (f"{_mhz(m.rate.default)}, {_mhz(m.rate.min)}, {_mhz(m.rate.max)}, " if m.rate
           else "0u, 0u, 0u, ")
        + f"ANV_NAME({_cstr(m.name)})}},"
        for m in t.messages])
    c += table("anv_param_desc_t", f"{tname}_params", [
        f"    {{{prm.index:#06x}u, {VT_C[prm.type.name]}, {_param_flags(prm)}, "
        f"{_value_init(prm.type, prm.default)}, {_value_init(prm.type, prm.min)}, "
        f"{_value_init(prm.type, prm.max)}, ANV_NAME({_cstr(prm.name)}), "
        f"ANV_NAME({_cstr(prm.unit)})}},"
        for prm in t.params])
    c += table("anv_action_desc_t", f"{tname}_actions", [
        f"    {{{a.index}u, {VT_C[a.arg.name] if a.arg else 'ANV_VT_NONE'}, "
        f"{'ANV_ACTION_DISARMED_ONLY' if a.disarmed_only else '0u'}, ANV_NAME({_cstr(a.name)})}},"
        for a in t.actions])
    c += table("anv_event_desc_t", f"{tname}_events", [
        f"    {{{e.code:#06x}u, {SEVERITY_C[e.severity]}u, ANV_NAME({_cstr(e.name)})}},"
        for e in t.events])
    c += [f"const anv_type_desc_t {tname}_type = {{",
          f"    ANV_NAME({_cstr(t.name)}), {t.type_id}u, {t.version}u, {t.wire_hash:#010x}u,",
          f"    {tname}_messages, {len(t.messages)}u,",
          f"    {tname}_params, {len(t.params)}u,",
          f"    {tname}_actions, {len(t.actions)}u,",
          f"    {tname}_events, {len(t.events)}u,", "};", ""]
    return "\n".join(h), "\n".join(c)


def _id_layout_decls(schema: Schema) -> list[str]:
    lay = schema.id_layout
    ids = schema.node_ids
    dst_bits = lay.get("dst").bits
    node_t = "uint8_t" if dst_bits <= 8 else "uint16_t"
    out = ["/* 29-bit identifier layout (protocol.yaml id_layout). */"]
    for f in lay.fields:
        out.append(f"#define ANV_ID_{f.name.upper()}_SHIFT {f.shift}u")
        out.append(f"#define ANV_ID_{f.name.upper()}_BITS {f.bits}u")
    out += [
        f"typedef {node_t} anv_node_id_t;",
        f"#define ANV_NODE_BROADCAST {ids.broadcast}u",
        f"#define ANV_NODE_UNASSIGNED {ids.unassigned}u",
        f"#define ANV_NODE_FIRST {ids.first}u",
        f"#define ANV_NODE_LAST {ids.last}u",
        f"#define ANV_PROTOCOL_LAST_PORT {schema.protocol_last_port}u",
        f"#define ANV_MAX_PORT {schema.max_port}u",
        "",
        "static inline uint32_t anv_id_make(uint8_t priority, anv_node_id_t dst, uint16_t port,",
        "                                   anv_node_id_t src)",
        "{",
        "    return ((uint32_t)(priority & ((1u << ANV_ID_PRIORITY_BITS) - 1u)) << ANV_ID_PRIORITY_SHIFT) |",
        "           ((uint32_t)(dst & ((1u << ANV_ID_DST_BITS) - 1u)) << ANV_ID_DST_SHIFT) |",
        "           ((uint32_t)(port & ((1u << ANV_ID_PORT_BITS) - 1u)) << ANV_ID_PORT_SHIFT) |",
        "           ((uint32_t)(src & ((1u << ANV_ID_SRC_BITS) - 1u)) << ANV_ID_SRC_SHIFT);",
        "}",
    ]
    for f, ct in (("priority", "uint8_t"), ("dst", "anv_node_id_t"), ("port", "uint16_t"),
                  ("src", "anv_node_id_t")):
        u = f.upper()
        out += [f"static inline {ct} anv_id_{f}(uint32_t id)",
                f"{{ return ({ct})((id >> ANV_ID_{u}_SHIFT) & ((1u << ANV_ID_{u}_BITS) - 1u)); }}"]
    out.append("")
    return out


def generate_all_types(schema: Schema) -> tuple[str, str]:
    """anv_all_types.h/.c: a table of every type, for hosts or tools written in C."""
    h = [HEADER.format(source="types/"), "#ifndef ANV_ALL_TYPES_H", "#define ANV_ALL_TYPES_H", "",
         '#include "anv_protocol.h"']
    for t in sorted(schema.types.values(), key=lambda t: t.type_id):
        h.append(f'#include "anv_{t.name}.h"')
    h += ["", "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
          f"#define ANV_N_TYPES {len(schema.types)}u",
          "extern const anv_type_desc_t *const anv_all_types[];",
          "/* NULL if no type has this ID. */",
          "const anv_type_desc_t *anv_type_by_id(uint16_t type_id);", "",
          "#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]
    rows = [f"    &anv_{t.name}_type," for t in sorted(schema.types.values(), key=lambda t: t.type_id)]
    c = [HEADER.format(source="types/"), '#include "anv_all_types.h"', "",
         "const anv_type_desc_t *const anv_all_types[] = {", *rows, "    NULL,", "};", "",
         "const anv_type_desc_t *anv_type_by_id(uint16_t type_id)", "{",
         "    for (unsigned i = 0; anv_all_types[i] != NULL; i++) {",
         "        if (anv_all_types[i]->type_id == type_id) {",
         "            return anv_all_types[i];", "        }", "    }",
         "    return NULL;", "}", ""]
    return "\n".join(h), "\n".join(c)


def generate(schema: Schema) -> dict[str, str]:
    """file name -> contents, for everything in schema/generated/c/."""
    files = {"anv_schema.h": RUNTIME_H}
    h, c = generate_type(schema, schema.protocol)
    files["anv_protocol.h"], files["anv_protocol.c"] = h, c
    for t in schema.types.values():
        h, c = generate_type(schema, t)
        files[f"anv_{t.name}.h"], files[f"anv_{t.name}.c"] = h, c
    files["anv_all_types.h"], files["anv_all_types.c"] = generate_all_types(schema)
    return files
